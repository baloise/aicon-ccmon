#!/usr/bin/env bash
# Render the collected usage history as a self-contained HTML page.
# No CDN, no network: the data and the drawing library are embedded, so the file
# works offline and the .ccmon-viz div pastes straight into a Confluence HTML macro.

set -uo pipefail
CLAUDE_DIR="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
CCMON_DIR="$CLAUDE_DIR/ccmon"
HISTORY_DIR="$CCMON_DIR/history"
OUT="${1:-$CCMON_DIR/chart.html}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# The drawing code is shared with the wallboard; inline whichever copy is around.
LIB=""
for c in "$HERE/../wallboard/chart-lib.js" "$CCMON_DIR/chart-lib.js" "$HERE/chart-lib.js"; do
  [ -f "$c" ] && { LIB="$c"; break; }
done
[ -n "$LIB" ] || { echo "chart-lib.js not found - run ./ccmon to install it" >&2; exit 1; }

shopt -s nullglob
files=("$HISTORY_DIR"/data/*.jsonl)
if [ ${#files[@]} -eq 0 ]; then
  echo "no history yet at $HISTORY_DIR/data/ - run ./ccmon first" >&2
  exit 1
fi

# Merge every machine's samples, sort by time, drop duplicate timestamps.
data=$(cat "${files[@]}" | jq -s -c 'map(select(.t != null)) | sort_by(.t) | unique_by(.t)')
n=$(printf '%s' "$data" | jq 'length')
[ "$n" -gt 0 ] || { echo "no samples recorded yet" >&2; exit 1; }

tmpl=$(mktemp)
cat > "$tmpl" <<'HTML'
<!doctype html>
<meta charset="utf-8">
<title>Claude usage history</title>
<div class="ccmon-viz">
<style>
.ccmon-viz{
  --surface-1:#fcfcfb; --text-primary:#0b0b0b; --text-secondary:#52514e; --text-muted:#82817c;
  --grid:#e6e5e1; --s1:#2a78d6; --s2:#eb6834;
  background:var(--surface-1); color:var(--text-primary);
  font:14px/1.5 ui-sans-serif,system-ui,-apple-system,"Segoe UI",sans-serif;
  padding:20px; max-width:960px; margin:0 auto; box-sizing:border-box;
}
@media (prefers-color-scheme:dark){
  .ccmon-viz{
    --surface-1:#1a1a19; --text-primary:#fff; --text-secondary:#c3c2b7; --text-muted:#8f8e86;
    --grid:#33322f; --s1:#3987e5; --s2:#d95926;
  }
}
.ccmon-viz h1{font-size:18px;margin:0 0 2px;font-weight:600}
.ccmon-viz h2{font-size:14px;margin:22px 0 2px;font-weight:600}
.ccmon-viz .sub{color:var(--text-secondary);font-size:12.5px;margin:0 0 4px}
.ccmon-viz figure{margin:0}
.ccmon-viz svg{display:block;width:100%;height:auto;overflow:visible}
.ccmon-viz .legend{display:flex;gap:16px;flex-wrap:wrap;font-size:12.5px;
  color:var(--text-secondary);margin:6px 0 0}
.ccmon-viz .legend span{display:inline-flex;align-items:center;gap:6px}
.ccmon-viz .sw{width:10px;height:10px;border-radius:2px;flex:none}
.ccmon-viz .gl{stroke:var(--grid);stroke-width:1}
.ccmon-viz .ax{fill:var(--text-muted);font-size:11px}
.ccmon-viz .ln{fill:none;stroke-width:2;stroke-linejoin:round;stroke-linecap:round}
.ccmon-viz .cross{stroke:var(--text-muted);stroke-width:1;stroke-dasharray:3 3}
.ccmon-viz .tip{position:absolute;pointer-events:none;background:var(--surface-1);
  border:1px solid var(--grid);border-radius:6px;padding:6px 9px;font-size:12.5px;
  box-shadow:0 2px 10px rgba(0,0,0,.14);white-space:nowrap;opacity:0;transition:opacity .1s}
.ccmon-viz .wrap{position:relative}
.ccmon-viz details{margin-top:26px;font-size:12.5px;color:var(--text-secondary)}
.ccmon-viz summary{cursor:pointer;color:var(--text-primary)}
.ccmon-viz table{border-collapse:collapse;margin-top:10px;width:100%}
.ccmon-viz th,.ccmon-viz td{text-align:right;padding:3px 10px 3px 0;
  border-bottom:1px solid var(--grid);font-variant-numeric:tabular-nums}
.ccmon-viz th:first-child,.ccmon-viz td:first-child{text-align:left}
.ccmon-viz .foot{color:var(--text-muted);font-size:12px;margin-top:22px}
</style>

<h1>Claude usage history</h1>
<p class="sub" id="ccmon-meta"></p>

<h2>7-day window</h2>
<p class="sub">Weekly quota.</p>
<figure class="wrap"><div id="c1"></div><div class="tip" id="t1"></div>
<div class="legend">
  <span><i class="sw" style="background:var(--s1)"></i>All models</span>
  <span id="ccmon-scope-legend" hidden><i class="sw" style="background:var(--s2)"></i><b id="ccmon-scope-name"></b></span>
</div></figure>

<h2>5-hour window</h2>
<p class="sub">Session quota, sawtoothing as each window rolls over.</p>
<figure class="wrap"><div id="c2"></div><div class="tip" id="t2"></div></figure>

<details>
  <summary>Data table</summary>
  <table id="ccmon-table"><thead><tr>
    <th>Time</th><th>5h</th><th>7d</th><th id="ccmon-scope-col">Scoped</th>
  </tr></thead><tbody></tbody></table>
</details>

<p class="foot">Generated by ccmon. Percentages are of each window's quota.</p>

<script>__LIB__</script>
<script>
const RAW = __DATA__;
const scopeKey = CCMON.scopeKey(RAW);

if (scopeKey) {
  document.getElementById('ccmon-scope-legend').hidden = false;
  document.getElementById('ccmon-scope-name').textContent = scopeKey;
  document.getElementById('ccmon-scope-col').textContent = scopeKey;
}

CCMON.draw(document.getElementById('c1'), document.getElementById('t1'), [
  { label: 'All models', color: 'var(--s1)', pts: RAW.map(d => ({ t: d.t, v: d.seven_day ?? null })) },
  ...(scopeKey ? [{ label: scopeKey, color: 'var(--s2)',
      pts: RAW.map(d => ({ t: d.t, v: (d.scoped || {})[scopeKey] ?? null })) }] : [])
], RAW);

// Single series, named by its heading and end label: slot 1, like any chart's
// first line. The palette's green slot stays unused - see wallboard/index.html.
CCMON.draw(document.getElementById('c2'), document.getElementById('t2'), [
  { label: 'Session', color: 'var(--s1)', pts: RAW.map(d => ({ t: d.t, v: d.five_hour ?? null })) }
], RAW);

document.getElementById('ccmon-meta').textContent =
  `${RAW.length} samples, ${CCMON.fmtDay(RAW[0].t)} to ${CCMON.fmtDay(RAW[RAW.length - 1].t)}`;

document.querySelector('#ccmon-table tbody').innerHTML = RAW.slice().reverse().slice(0, 500)
  .map(d => `<tr><td>${CCMON.fmtFull(d.t)}</td><td>${d.five_hour ?? '-'}</td><td>${d.seven_day ?? '-'}</td><td>${scopeKey ? ((d.scoped || {})[scopeKey] ?? '-') : '-'}</td></tr>`).join('');
</script>
</div>
HTML

datafile=$(mktemp)
printf '%s' "$data" > "$datafile"
python3 - "$tmpl" "$OUT" "$datafile" "$LIB" <<'INJECT'
import sys, pathlib
tmpl, out, datafile, lib = sys.argv[1:5]
html = pathlib.Path(tmpl).read_text()
html = html.replace('__LIB__', pathlib.Path(lib).read_text())
html = html.replace('__DATA__', pathlib.Path(datafile).read_text())
pathlib.Path(out).write_text(html)
INJECT
rm -f "$tmpl" "$datafile"
echo "wrote $OUT ($n samples)"
